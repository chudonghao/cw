bool Equal(int left, int right) { return left == right; }

bool NotEqual(int left, int right) { return left != right; }

bool Less(int left, int right) { return left < right; }

bool LessEqual(int left, int right) { return left <= right; }

bool Greater(int left, int right) { return left > right; }

bool GreaterEqual(int left, int right) { return left >= right; }

bool BooleanEqual(bool left, bool right) { return left == right; }

bool BooleanNotEqual(bool left, bool right) { return left != right; }
